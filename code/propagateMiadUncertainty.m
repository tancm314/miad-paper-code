function [rmse_components,rmse_attitude,rmse_angle,denominator_a_i, ...
    denominator_cross] = propagateMiadUncertainty(i,j,observed_a,observed_b, ...
    sigma_a_i1,sigma_a_i2,sigma_b_j)
% Propagate primary-component noise to reconstructed components and attitude.

a_i = observed_a(i);
a_i1 = observed_a(cyclicIndex(i,1));
a_i2 = observed_a(cyclicIndex(i,2));
b_j = observed_b(j);
b_j1 = observed_b(cyclicIndex(j,1));
b_j2 = observed_b(cyclicIndex(j,2));
b_i = observed_b(i);
b_i1 = observed_b(cyclicIndex(i,1));
b_i2 = observed_b(cyclicIndex(i,2));
a_j = observed_a(j);
a_j1 = observed_a(cyclicIndex(j,1));
a_j2 = observed_a(cyclicIndex(j,2));

system_matrix = [a_i, 0, 0; ...
    0, b_j1, b_j2; ...
    b_i, a_j1, a_j2];
measurement_matrix = -[a_i1, a_i2, 0; ...
    0, 0, b_j; ...
    b_i1, b_i2, a_j];
component_jacobian = system_matrix \ measurement_matrix;
primary_covariance = diag([sigma_a_i1^2;sigma_a_i2^2;sigma_b_j^2]);
component_covariance = component_jacobian * primary_covariance * component_jacobian';
rmse_components = sqrt(diag(component_covariance));

attitude_jacobian = [-vectorToSkewMatrix(observed_a); ...
    -vectorToSkewMatrix(observed_b)];
row_a_i1 = zeros(1,3);
row_a_i1(cyclicIndex(i,1)) = 1;
row_a_i2 = zeros(1,3);
row_a_i2(cyclicIndex(i,2)) = 1;
row_b_j = zeros(1,3);
row_b_j(j) = 1;
selection_matrix = [row_a_i1,zeros(1,3); ...
    row_a_i2,zeros(1,3);zeros(1,3),row_b_j];
inverse_attitude_jacobian = (selection_matrix * attitude_jacobian) \ eye(3);
attitude_covariance = inverse_attitude_jacobian * primary_covariance ...
    * inverse_attitude_jacobian';

switch i
    case j
        summed_variance = sum([(a_j^2*b_i1^2+a_i1^2*(b_j1^2+b_j2^2)) ...
            / a_i^2 / (a_j1*b_j2-a_j2*b_j1)^2; ...
            (a_j^2*b_i2^2+a_i2^2*(b_j1^2+b_j2^2)) ...
            / a_i^2 / (a_j1*b_j2-a_j2*b_j1)^2; ...
            1/(a_j1*b_j2-a_j2*b_j1)^2] .* ...
            [sigma_a_i1^2;sigma_a_i2^2;sigma_b_j^2]);
    case cyclicIndex(j,1)
        summed_variance = sum([1/a_i^2; ...
            (a_j^2*b_i^2+a_i^2*(b_j1^2+b_j2^2)) ...
            / a_i^2 / (a_j1*b_j2-a_j2*b_j1)^2; ...
            1/(a_j1*b_j2-a_j2*b_j1)^2] .* ...
            [sigma_a_i1^2;sigma_a_i2^2;sigma_b_j^2]);
    case cyclicIndex(j,2)
        summed_variance = sum([(a_j^2*b_i^2+a_i^2*(b_j1^2+b_j2^2)) ...
            / a_i^2 / (a_j1*b_j2-a_j2*b_j1)^2; ...
            1/a_i^2; ...
            1/(a_j1*b_j2-a_j2*b_j1)^2] .* ...
            [sigma_a_i1^2;sigma_a_i2^2;sigma_b_j^2]);
end
rmse_attitude = sqrt(diag(attitude_covariance));
rmse_angle = sqrt(summed_variance);
denominator_a_i = a_i;
denominator_cross = a_j2*b_j1-a_j1*b_j2;
end
